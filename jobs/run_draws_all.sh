#!/bin/bash
# 40-draw inner CV for BOTH arms, all six datasets, symmetric.
#
# Why: fracture's selector failure was DRAW variance, not fold variance. Averaging the
# inner CV over 40 fresh draws of 25 volumes (seeds 105-144, disjoint from the reporting
# draws 5-104) flips rank agreement with test from -0.60 to +0.60 on fracture and ranks the
# two parity configs 1st and 2nd. 32 fold shuffles of the SAME five draws made it worse.
#
# Symmetry: the spectral config AND the spatial patch are both selected this way, or the
# comparison reverts to tuned-vs-untuned. 8 blocks of 5 draws so partial progress is usable
# and each block is an independent estimate of the same quantity.
set -u
PY=/opt/dpeekenv/bin/python
OUT=/workspace/results/medmnist_cvdraws
TSV=/tmp/claude-6269505/-workspace/cb72acaf-48d3-4307-9277-3cbe75d63ca5/scratchpad/draws_all.tsv
PAR=${PAR:-8}
sem(){ while [ "$(jobs -rp|wc -l)" -ge "$PAR" ]; do wait -n; done; }
echo "=== start $(date +%H:%M:%S)"
# 10 blocks of 5 fresh draws = 50 draws total, read out at 25 (blocks 0-4), 40 (0-7) and
# 50 (0-9) so the selection can be shown stable in the draw count rather than reported at
# one k. Resumable: a block whose medmnist_cv.csv exists is skipped, so re-running this
# script only executes what is missing.
# 20 blocks of 5 fresh draws = 100 draws (seeds 105-204), read out at 10, 25, 40, 50 and
# 100 so the selection can be shown as a function of draw count. Reporting draws are
# 5-104 and are never touched. Resumable: a block with medmnist_cv.csv is skipped.
# DO NOT EDIT THIS FILE WHILE IT RUNS -- bash re-reads by byte offset and the parse broke
# mid-run on 2026-10-22 when blocks 8-9 were appended during execution.
for blk in $(seq 0 19); do
  s0=$((105 + blk*5))
  # ---- spectral arm: the family the property rule assigns, every config in it
  while IFS=$'\t' read -r ds p cfg e npz; do
    o=$OUT/$ds/$cfg/d$s0
    [ -f "$o/medmnist_cv.csv" ] && continue
    # fracture's magnitude family was already run under the flat layout; reuse it
    old=$OUT/$cfg/d$s0
    if [ "$ds" = fracturemnist3d ] && [ -f "$old/medmnist_cv.csv" ]; then
      mkdir -p "$o"; cp "$old/medmnist_cv.csv" "$o/"; continue
    fi
    sem; mkdir -p "$o"
    env $e MEDMNIST_CV_SEED0=$s0 MEDMNIST_SEEDS=5 MEDMNIST_CVK=5 MEDMNIST_N=25 \
        MEDMNIST_CVSEED=0 MEDMNIST_PATCH=$p MEDMNIST_ARM=$cfg \
        MEDMNIST_NPZ=$npz MEDMNIST_OUT=$o \
        $PY medmnist_cv.py > "$o/log.txt" 2>&1 &
  done < $TSV
  # ---- spatial arm: the same patch grid {4,7,14} used in both tables
  for ds in organmnist3d nodulemnist3d adrenalmnist3d fracturemnist3d vesselmnist3d synapsemnist3d; do
    npz=/workspace/data/medmnist/$ds.npz
    [ "$ds" = organmnist3d ] && npz=/agent-home/medmnist/organmnist3d.npz
    for p in 4 7 14; do
      o=$OUT/$ds/spatial_p$p/d$s0
      [ -f "$o/medmnist_cv.csv" ] && continue
      sem; mkdir -p "$o"
      env MEDMNIST_CV_ARM=spatial MEDMNIST_CV_SEED0=$s0 MEDMNIST_SEEDS=5 MEDMNIST_CVK=5 \
          MEDMNIST_N=25 MEDMNIST_CVSEED=0 MEDMNIST_PATCH=$p MEDMNIST_ARM=spatial_p$p \
          MEDMNIST_NPZ=$npz MEDMNIST_OUT=$o \
          $PY medmnist_cv.py > "$o/log.txt" 2>&1 &
    done
  done
  echo "block $blk (draws $s0-$((s0+4))) dispatched $(date +%H:%M:%S)"
done
wait
echo "=== done $(date +%H:%M:%S)"
